function fixRussianTypography(rootNode = document.body) {
  if (root.lang !== 'ru') return;
  const skip = new Set(['SCRIPT', 'STYLE', 'CODE', 'PRE']);
  const walker = document.createTreeWalker(rootNode, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (!node.parentElement || skip.has(node.parentElement.tagName)) continue;
    node.nodeValue = node.nodeValue.replace(
      /(^|[\s([{«„])(и|а|но|или|либо|да|в|во|на|с|со|к|ко|у|о|об|обо|от|до|по|под|над|за|из|изо|для|при|про|без|через|между|перед|после|не|ни|что|как)\s+/giu,
      (m, p, w) => p + w + '\u00A0'
    );
  }
}

function setLanguage(lang) {
  const d = translations[lang] || translations.ru;
  root.lang = lang;
  document.title = lang === 'ru'
    ? 'Алексей Савиных — Product / UX / UI Designer'
    : 'Alexey Savinykh — Product / UX / UI Designer';
  if (metaDescription) metaDescription.content = d.metaDescription;

  document.querySelectorAll('[data-i18n]').forEach(node => {
    const value = d[node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(node => {
    const value = d[node.dataset.i18nAria];
    if (value) node.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(node => {
    const value = d[node.dataset.i18nTitle];
    if (value) node.setAttribute('title', value);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(node => {
    const value = d[node.dataset.i18nAlt];
    if (value) node.setAttribute('alt', value);
  });

  buttons.forEach(button => {
    const active = button.dataset.lang === lang;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  caseLinks.forEach(link => {
    link.href = lang === 'en' ? 'domovyonok-en.html' : 'domovyonok.html';
  });

  fixRussianTypography();
  localStorage.setItem('portfolio-language', lang);
}

buttons.forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.lang)));
menu?.addEventListener('click', () => {
  const open = menu.getAttribute('aria-expanded') === 'true';
  menu.setAttribute('aria-expanded', String(!open));
  panel.hidden = open;
});
document.querySelectorAll('.mobile-panel a').forEach(a => a.addEventListener('click', () => {
  menu.setAttribute('aria-expanded', 'false');
  panel.hidden = true;
}));

const reduced = matchMedia('(prefers-reduced-motion: reduce)').matches;
if (!reduced && 'IntersectionObserver' in window) {
  const observer = new IntersectionObserver(entries => entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('is-visible');
      observer.unobserve(entry.target);
    }
  }), { threshold: .06 });
  document.querySelectorAll('.reveal').forEach(el => observer.observe(el));
} else {
  document.querySelectorAll('.reveal').forEach(el => el.classList.add('is-visible'));
}

const urlLang = new URLSearchParams(location.search).get('lang');
setLanguage(urlLang === 'en' || urlLang === 'ru' ? urlLang : (localStorage.getItem('portfolio-language') || 'ru'));
document.getElementById('year').textContent = new Date().getFullYear();

document.querySelectorAll('[data-back-top]').forEach(button => button.addEventListener('click', e => {
  e.preventDefault();
  window.scrollTo({ top: 0, left: 0, behavior: reduced ? 'auto' : 'smooth' });
  setTimeout(() => {
    document.documentElement.scrollTop = 0;
    document.body.scrollTop = 0;
  }, reduced ? 0 : 450);
}));

const caseModal = document.getElementById('case-modal');
const caseMail = document.getElementById('case-modal-mail');
document.querySelectorAll('[data-private-project]').forEach(button => button.addEventListener('click', () => {
  const name = button.dataset.privateProject === 'mts' ? 'MTS' : 'Sephora';
  caseMail.href = `mailto:ogastas@icloud.com?subject=${encodeURIComponent('Portfolio case request — ' + name)}`;
  caseModal.hidden = false;
  document.body.style.overflow = 'hidden';
  caseModal.querySelector('.case-modal-close').focus();
}));
document.querySelectorAll('[data-modal-close]').forEach(button => button.addEventListener('click', () => {
  caseModal.hidden = true;
  document.body.style.overflow = '';
}));
document.addEventListener('keydown', e => {
  if (e.key === 'Escape' && !caseModal.hidden) {
    caseModal.hidden = true;
    document.body.style.overflow = '';
  }
});

const headerEl = document.querySelector('.site-header');
function scrollToSection(target, smooth = true) {
  if (!target) return;
  const headerH = headerEl?.getBoundingClientRect().height || 0;
  const y = target.getBoundingClientRect().top + window.scrollY - headerH - 16;
  window.scrollTo({ top: Math.max(0, y), left: 0, behavior: (smooth && !reduced) ? 'smooth' : 'auto' });
}
document.querySelectorAll('a[href^="#"]').forEach(a => {
  const href = a.getAttribute('href');
  if (!href || href === '#' || href === '#top' || a.matches('[data-back-top]')) return;
  const target = document.querySelector(href);
  if (!target) return;
  a.addEventListener('click', e => {
    e.preventDefault();
    scrollToSection(target, true);
    history.replaceState(null, '', href);
  });
});

document.querySelectorAll('.profile-placeholder').forEach(a => a.addEventListener('click', e => e.preventDefault()));

const floatingTop = document.querySelector('.floating-back-top');
function updateFloatingTop() {
  if (!floatingTop) return;
  floatingTop.classList.toggle('is-visible', window.scrollY > 520);
}
window.addEventListener('scroll', updateFloatingTop, { passive: true });
updateFloatingTop();
